import { describe, expect, it } from "bun:test";
import { compactTokens, compactTypography, renderTokenModule } from "./runtime-tokens";

describe("runtime token generation", () => {
  it("uses markers only when deriving the key reproduces the exact source suffix", () => {
    expect(
      compactTokens(
        {
          fg: { brandContrast: "var(--test-fg-brand-contrast)" },
          palette: { gray100: "var(--test-palette-gray-100)" },
          x1: "var(--test-x1)",
          alias: "var(--test-other)",
          literal: "0",
        },
        "var(--test-",
      ),
    ).toEqual({
      "fg.brandContrast": 0,
      "palette.gray100": 0,
      x1: "x1",
      alias: "other",
      literal: ["0"],
    });
  });

  it("flattens namespaces and retains aliases and literal values", () => {
    const tokens = compactTokens(
      { fg: { neutral: "var(--test-gray-900)", alias: "var(--test-gray-900)" }, raw: "#fff" },
      "var(--test-",
    );
    expect(tokens).toEqual({ "fg.neutral": "gray-900", "fg.alias": "gray-900", raw: ["#fff"] });
  });

  it("keeps typography property order and accepts literal overrides", () => {
    const tokens = compactTypography({
      textStyleExample: {
        enabled: {
          root: {
            fontSize: "var(--seed-font-size-example)",
            lineHeight: "1.5",
            fontWeight: "var(--seed-font-weight-example)",
          },
        },
      },
    });
    expect(tokens).toEqual({ Example: ["example", ["1.5"], "example"] });
  });

  it("renders the complete deterministic source", () => {
    expect(renderTokenModule({ testTokens: { a: "a", b: ["inherit"] } })).toBe(
      "// Generated by scripts/generate-runtime-tokens.ts. Do not edit.\n" +
        'export const testTokens = {\n  "a": "a",\n  "b": [\n    "inherit"\n  ]\n};\n',
    );
  });
});
