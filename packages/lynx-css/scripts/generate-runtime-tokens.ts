import { vars } from "@seed-design/lynx-css/vars";
import { vars as typography } from "@seed-design/lynx-css/vars/component/typography";
import { compactTokens, compactTypography, renderTokenModule } from "./runtime-tokens";

const groups = {
  colorTokens: compactTokens(vars.$color, "var(--seed-color-"),
  dimensionTokens: compactTokens(vars.$dimension, "var(--seed-dimension-"),
  radiusTokens: compactTokens(vars.$radius, "var(--seed-radius-"),
  fontSizeTokens: compactTokens(vars.$fontSize, "var(--seed-font-size-"),
  fontWeightTokens: compactTokens(vars.$fontWeight, "var(--seed-font-weight-"),
  lineHeightTokens: compactTokens(vars.$lineHeight, "var(--seed-line-height-"),
  typographyTokens: compactTypography(typography),
};
await Bun.write(new URL("../vars/runtime.mjs", import.meta.url), renderTokenModule(groups));
await Bun.write(
  new URL("../vars/runtime.d.ts", import.meta.url),
  [
    "// Generated by scripts/generate-runtime-tokens.ts. Do not edit.",
    "export type EncodedToken = string | readonly [string];",
    "export type ScalarToken = EncodedToken | 0;",
    ...Object.keys(groups).map(
      (name) =>
        `export declare const ${name}: Readonly<Record<string, ${name === "typographyTokens" ? "readonly [EncodedToken, EncodedToken, EncodedToken]" : "ScalarToken"}>>;`,
    ),
    "",
  ].join("\n"),
);
