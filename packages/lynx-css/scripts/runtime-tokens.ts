export type EncodedToken = string | readonly [string];
export type ScalarToken = EncodedToken | 0;
export type TokenTree = { readonly [key: string]: string | TokenTree };

export function encodeToken(value: string, prefix: string): EncodedToken {
  return value.startsWith(prefix) && value.endsWith(")") ? value.slice(prefix.length, -1) : [value];
}

export function deriveTokenSuffix(key: string): string {
  return key
    .replace(/\./g, "-")
    .replace(/([a-z])([A-Z]|\d)/g, "$1-$2")
    .toLowerCase();
}

export function compactTokens(tree: TokenTree, prefix: string): Record<string, ScalarToken> {
  const result: Record<string, ScalarToken> = {};
  function visit(node: TokenTree, path: string[]) {
    for (const [key, value] of Object.entries(node)) {
      const next = [...path, key];
      if (typeof value === "string") {
        const key = next.join(".");
        const token = encodeToken(value, prefix);
        result[key] = typeof token === "string" && token === deriveTokenSuffix(key) ? 0 : token;
      } else visit(value, next);
    }
  }
  visit(tree, []);
  return result;
}

export interface TypographyTokens {
  readonly [key: string]: {
    readonly enabled: {
      readonly root: {
        readonly fontSize: string;
        readonly lineHeight: string;
        readonly fontWeight: string;
      };
    };
  };
}

export function compactTypography(tokens: TypographyTokens) {
  return Object.fromEntries(
    Object.entries(tokens).map(
      ([
        key,
        {
          enabled: { root },
        },
      ]) => [
        key.replace(/^textStyle/, ""),
        [
          encodeToken(root.fontSize, "var(--seed-font-size-"),
          encodeToken(root.lineHeight, "var(--seed-line-height-"),
          encodeToken(root.fontWeight, "var(--seed-font-weight-"),
        ],
      ],
    ),
  );
}

export function renderTokenModule(exports: Record<string, unknown>): string {
  return [
    "// Generated by scripts/generate-runtime-tokens.ts. Do not edit.",
    ...Object.entries(exports).map(
      ([name, tokens]) => `export const ${name} = ${JSON.stringify(tokens, null, 2)};`,
    ),
    "",
  ].join("\n");
}
